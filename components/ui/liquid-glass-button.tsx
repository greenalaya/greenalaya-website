/**
 * A clear "liquid glass" pill: the label sits inside a glass rim that distorts whatever is
 * behind it (the distortion runs in Chromium browsers; others show the rim alone).
 *
 * `asChild` puts the glass on the element you pass instead of a <button>, e.g. a Next <Link>,
 * so a navigation stays a real link.
 */
function LiquidButton({
  className,
  variant,
  size,
  asChild = false,
  children,
  ...props
}: React.ComponentProps<"button"> &
  VariantProps<typeof liquidbuttonVariants> & {
    asChild?: boolean;
  }) {
  const classes = cn("relative", liquidbuttonVariants({ variant, size, className }));

  if (asChild && React.isValidElement(children)) {
    const child = children as React.ReactElement<{
      className?: string;
      children?: React.ReactNode;
    }>;
    return React.cloneElement(
      child,
      { "data-slot": "button", className: cn(classes, child.props.className) } as Partial<
        typeof child.props
      >,
      <GlassLayers />,
      <span className="pointer-events-none z-10">{child.props.children}</span>,
      <GlassFilter />,
    );
  }

  return (
    <button data-slot="button" className={classes} {...props}>
      <GlassLayers />
      <span className="pointer-events-none z-10">{children}</span>
      <GlassFilter />
    </button>
  );
}

function GlassFilter() {
  return (
    <svg aria-hidden className="hidden">
      <defs>
        <filter
          id="container-glass"
          x="0%"
          y="0%"
          width="100%"
          height="100%"
          colorInterpolationFilters="sRGB"
        >
          {/* Generate turbulent noise for distortion */}
          <feTurbulence
            type="fractalNoise"
            baseFrequency="0.05 0.05"
            numOctaves="1"
            seed="1"
            result="turbulence"
          />

          {/* Blur the turbulence pattern slightly */}
          <feGaussianBlur in="turbulence" stdDeviation="2" result="blurredNoise" />

          {/* Displace the source graphic with the noise */}
          <feDisplacementMap
            in="SourceGraphic"
            in2="blurredNoise"
            scale="70"
            xChannelSelector="R"
            yChannelSelector="B"
            result="displaced"
          />

          {/* Apply overall blur on the final result */}
          <feGaussianBlur in="displaced" stdDeviation="4" result="finalBlur" />

          {/* Output the result */}
          <feComposite in="finalBlur" in2="finalBlur" operator="over" />
        </filter>
      </defs>
    </svg>
  );
}

export { LiquidButton, liquidbuttonVariants };
